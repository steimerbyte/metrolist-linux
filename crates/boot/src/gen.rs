//! Parsing and rendering for `crates/*/module.meta` files.
//!
//! Shared by the build script (which generates the registry) and the unit tests.

/// One parsed `module.meta` entry.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Meta {
    pub name: String,
    pub label: String,
    pub order: u16,
    pub init: Option<String>,
}

/// Parses one `module.meta` file; `name` is the crate directory name.
pub fn parse_meta(name: &str, text: &str) -> Result<Meta, String> {
    let mut label: Option<String> = None;
    let mut order: Option<u16> = None;
    let mut init: Option<String> = None;

    for (line_no, raw) in text.lines().enumerate() {
        let line = raw.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let (key, value) = match line.split_once('=') {
            Some(parts) => parts,
            None => {
                return Err(format!(
                    "{name}: line {}: expected `key = value`",
                    line_no + 1
                ));
            }
        };
        let key = key.trim();
        let value = unquote(value.trim());
        match key {
            "label" => {
                if label.is_some() {
                    return Err(format!("{name}: duplicate key `label`"));
                }
                let valid = !value.is_empty()
                    && value
                        .chars()
                        .all(|c| matches!(c, 'A'..='Z' | '0'..='9' | ' '));
                if !valid {
                    return Err(format!(
                        "{name}: `label` must be non-empty and only A-Z, 0-9 or space: `{value}`"
                    ));
                }
                label = Some(value.to_owned());
            }
            "order" => {
                if order.is_some() {
                    return Err(format!("{name}: duplicate key `order`"));
                }
                let parsed = value
                    .parse::<u16>()
                    .map_err(|_| format!("{name}: `order` is not a u16: `{value}`"))?;
                order = Some(parsed);
            }
            "init" => {
                if init.is_some() {
                    return Err(format!("{name}: duplicate key `init`"));
                }
                if value.is_empty() {
                    return Err(format!("{name}: `init` must not be empty"));
                }
                init = Some(value.to_owned());
            }
            _ => return Err(format!("{name}: unknown key `{key}`")),
        }
    }

    let label = label.ok_or_else(|| format!("{name}: missing `label`"))?;
    let order = order.ok_or_else(|| format!("{name}: missing `order`"))?;
    Ok(Meta {
        name: name.to_owned(),
        label,
        order,
        init,
    })
}

/// Renders the registry as the `modules.rs` include: sorted by order, ties by name.
/// Duplicate orders are rejected because the boot sequence needs a total order.
pub fn render(entries: &[Meta]) -> Result<String, String> {
    if entries.is_empty() {
        return Err("no module.meta files found".to_owned());
    }
    let mut sorted: Vec<&Meta> = entries.iter().collect();
    sorted.sort_by(|a, b| a.order.cmp(&b.order).then_with(|| a.name.cmp(&b.name)));

    for pair in sorted.windows(2) {
        if pair[0].order == pair[1].order {
            let names: Vec<&str> = sorted
                .iter()
                .filter(|m| m.order == pair[0].order)
                .map(|m| m.name.as_str())
                .collect();
            return Err(format!(
                "duplicate order {}: {}",
                pair[0].order,
                names.join(", ")
            ));
        }
    }

    let mut out = String::from(
        "// @generated by crates/boot/build.rs from crates/*/module.meta — do not edit.\n[\n",
    );
    for m in &sorted {
        let init = match &m.init {
            Some(path) => format!("Some({path})"),
            None => "None".to_owned(),
        };
        out.push_str(&format!(
            "    Module {{ name: \"{}\", label: \"{}\", order: {}, init: {} }},\n",
            m.name, m.label, m.order, init
        ));
    }
    out.push_str("]\n");
    Ok(out)
}

fn unquote(value: &str) -> &str {
    let bytes = value.as_bytes();
    let quoted = bytes.len() >= 2
        && (bytes[0] == b'"' || bytes[0] == b'\'')
        && bytes[bytes.len() - 1] == bytes[0];
    if quoted {
        &value[1..value.len() - 1]
    } else {
        value
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn entry(name: &str, label: &str, order: u16) -> Meta {
        Meta {
            name: name.to_owned(),
            label: label.to_owned(),
            order,
            init: None,
        }
    }

    #[test]
    fn render_rejects_empty_list() {
        assert!(render(&[]).is_err());
    }

    #[test]
    fn render_sorts_by_order() {
        let entries = [entry("store", "STORE", 20), entry("core", "CORE", 10)];
        let rendered = render(&entries).unwrap();
        let core = rendered.find("name: \"core\"").unwrap();
        let store = rendered.find("name: \"store\"").unwrap();
        assert!(core < store);
        assert!(rendered.starts_with("// @generated by crates/boot/build.rs"));
        assert!(rendered.ends_with("]\n"));
    }

    #[test]
    fn render_ties_equal_orders_by_name() {
        let entries = [entry("b", "B", 20), entry("a", "A", 20)];
        assert_eq!(render(&entries).unwrap_err(), "duplicate order 20: a, b");
    }

    #[test]
    fn render_rejects_duplicate_order() {
        let entries = [
            entry("core", "CORE", 10),
            entry("store", "STORE", 20),
            entry("ui", "UI", 20),
        ];
        assert_eq!(
            render(&entries).unwrap_err(),
            "duplicate order 20: store, ui"
        );
    }

    #[test]
    fn render_keeps_init_path_unquoted() {
        let mut store = entry("store", "STORE", 20);
        store.init = Some("ml_store::boot_init".to_owned());
        let rendered = render(&[store]).unwrap();
        assert!(rendered.contains("init: Some(ml_store::boot_init) }"));
        assert!(!rendered.contains("Some(\""));
    }

    #[test]
    fn parse_meta_reads_quoted_values_and_comments() {
        let text = "# ignored\n\nlabel = \"STORE\"\norder = 20\ninit = 'ml_store::boot_init'\n";
        let got = parse_meta("store", text).unwrap();
        let want = Meta {
            name: "store".to_owned(),
            label: "STORE".to_owned(),
            order: 20,
            init: Some("ml_store::boot_init".to_owned()),
        };
        assert_eq!(got, want);
    }

    #[test]
    fn parse_meta_rejects_unknown_key() {
        let err = parse_meta("store", "label = STORE\norder = 20\ncolor = red\n").unwrap_err();
        assert!(err.contains("store"), "{err}");
        assert!(err.contains("color"), "{err}");
    }

    #[test]
    fn parse_meta_requires_label() {
        let err = parse_meta("store", "order = 20\n").unwrap_err();
        assert!(err.contains("store"), "{err}");
        assert!(err.contains("label"), "{err}");
    }

    #[test]
    fn parse_meta_requires_order() {
        let err = parse_meta("store", "label = STORE\n").unwrap_err();
        assert!(err.contains("store"), "{err}");
        assert!(err.contains("order"), "{err}");
    }

    #[test]
    fn parse_meta_rejects_non_u16_order() {
        let err = parse_meta("store", "label = STORE\norder = abc\n").unwrap_err();
        assert!(err.contains("order"), "{err}");
    }

    #[test]
    fn parse_meta_rejects_lowercase_label() {
        let err = parse_meta("store", "label = Store\norder = 20\n").unwrap_err();
        assert!(err.contains("label"), "{err}");
    }

    #[test]
    fn parse_meta_rejects_duplicate_key() {
        let err = parse_meta("store", "label = STORE\nlabel = STORE\norder = 20\n").unwrap_err();
        assert!(err.contains("duplicate"), "{err}");
    }
}
